"""Safety Gate v2 Phase 8 — regression tests built from the engineering
dataset (tests/data/safety_gate_v2_regression.jsonl).

See docs/SAFETY_REGRESSION_DATASET.md. Only ENGINEERING_CONFIDENT cases are
used as hard pass/fail assertions here — NEEDS_CLINICAL_REVIEW cases are
loaded and reported on for visibility (so a case existing in the dataset is
never silently forgotten) but never turned into a routing assertion, per
Phase 8's explicit instruction not to guess medically-correct routing.

This file intentionally does not hand-write a test function per case
(117 of them) — one parametrized test loads the whole dataset.
"""

import json
from pathlib import Path

import pytest

from app.services.safety_decision import evaluate_safety_v2

DATASET_PATH = Path(__file__).resolve().parent / "data" / "safety_gate_v2_regression.jsonl"


def _load_dataset() -> list[dict]:
    with DATASET_PATH.open(encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


_ALL_CASES = _load_dataset()
_CONFIDENT_CASES = [c for c in _ALL_CASES if c["clinical_review_status"] == "ENGINEERING_CONFIDENT"]
_NEEDS_REVIEW_CASES = [
    c for c in _ALL_CASES if c["clinical_review_status"] == "NEEDS_CLINICAL_REVIEW"
]


def test_dataset_loads_and_has_no_duplicate_ids():
    assert len(_ALL_CASES) >= 80, "dataset should have at least ~80 cases per Phase 8's target size"
    ids = [c["id"] for c in _ALL_CASES]
    assert len(ids) == len(set(ids)), "duplicate case id in dataset"


def test_dataset_only_uses_the_two_approved_review_statuses():
    allowed = {"ENGINEERING_CONFIDENT", "NEEDS_CLINICAL_REVIEW"}
    statuses = {c["clinical_review_status"] for c in _ALL_CASES}
    assert statuses <= allowed, f"unexpected clinical_review_status value(s): {statuses - allowed}"


def test_dataset_only_uses_the_two_approved_provenance_values():
    allowed = {"regression_bug", "synthetic_engineering"}
    values = {c["provenance"] for c in _ALL_CASES}
    assert values <= allowed, f"unexpected provenance value(s): {values - allowed}"


@pytest.mark.parametrize(
    "case",
    _CONFIDENT_CASES,
    ids=[c["id"] for c in _CONFIDENT_CASES],
)
def test_engineering_confident_case_matches_current_routing(case):
    """The dataset's expected_* fields were generated by calling
    evaluate_safety_v2() against the real code (see
    scripts/generate_safety_regression_dataset.py) — this test re-runs
    that same call and asserts nothing has silently drifted since."""
    decision = evaluate_safety_v2(case["input"], locale_code=case["language"])

    actual_category = decision.category.value if decision.category else None
    assert actual_category == case["expected_category"], (
        f"[{case['id']}] category drifted: expected {case['expected_category']!r}, "
        f"got {actual_category!r} — {case['notes']}"
    )
    assert decision.risk_level.value == case["expected_risk_level"], (
        f"[{case['id']}] risk_level drifted"
    )
    assert decision.action.value == case["expected_action"], f"[{case['id']}] action drifted"
    assert decision.allow_rag == case["expected_allow_rag"], f"[{case['id']}] allow_rag drifted"
    assert decision.allow_llm == case["expected_allow_llm"], f"[{case['id']}] allow_llm drifted"
    assert (not decision.allow_llm) == case["expected_short_circuit"], (
        f"[{case['id']}] short-circuit expectation drifted"
    )
    assert decision.source.value == case["expected_source"], f"[{case['id']}] source drifted"


def test_needs_clinical_review_cases_are_loaded_but_not_asserted():
    """NEEDS_CLINICAL_REVIEW cases must exist in the dataset (so they're
    visible and trackable) but this test deliberately does not assert
    their routing is correct — see docs/SAFETY_REGRESSION_DATASET.md."""
    assert len(_NEEDS_REVIEW_CASES) > 0
    for case in _NEEDS_REVIEW_CASES:
        assert case["notes"], (
            f"[{case['id']}] NEEDS_CLINICAL_REVIEW case must explain the ambiguity"
        )


# ---------------------------------------------------------------------------
# A small endpoint-level subset — proves the dataset's expectations also
# hold through the real HTTP request path, not just the pure decision
# function. Deliberately a handful of representative cases, not all 109.
# ---------------------------------------------------------------------------


def _case(case_id: str) -> dict:
    for c in _ALL_CASES:
        if c["id"] == case_id:
            return c
    raise KeyError(case_id)


_ENDPOINT_SUBSET_IDS = [
    "rw_001",  # low, normal path
    "mr_001",  # moderate, medication_risk
    "ac_001",  # high, acute_change
    "sh_001",  # emergency, self_harm (deterministic gate)
    "bd_004",  # emergency, breathing_difficulty (independent detector only)
    "ty_001",  # emergency, life_threat (classifier, typo)
    "bl_002",  # low, benign "passed out flyers"
]


@pytest.mark.parametrize("case_id", _ENDPOINT_SUBSET_IDS)
async def test_endpoint_level_subset_matches_dataset_expectations(client, mock_llm, case_id):
    case = _case(case_id)
    profile_resp = await client.post(
        "/api/profiles",
        json={
            "disease_stage": "middle",
            "behavioral_patterns": ["wandering"],
            "calming_strategies": ["music"],
            "safety_concerns": ["fall risk"],
        },
    )
    access_code = profile_resp.json()["access_code"]

    resp = await client.post(
        "/api/coach/chat",
        json={"access_code": access_code, "patient_name": "Mom", "message": case["input"]},
    )
    assert resp.status_code == 200

    saw_normal_llm_output = False
    for line in resp.text.splitlines():
        if not line.startswith("data: "):
            continue
        data = line[len("data: ") :]
        if data == "[DONE]":
            continue
        parsed = json.loads(data)
        if parsed.get("text") == "This is " or parsed.get("replace", "").startswith("This is"):
            saw_normal_llm_output = True

    # If the dataset says LLM was skipped, the mock's canned chunks must
    # never appear; if it says LLM ran, they must.
    assert saw_normal_llm_output == case["expected_allow_llm"], (
        f"[{case_id}] endpoint-level LLM usage didn't match dataset expectation"
    )
